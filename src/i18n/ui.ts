/** Prefix an English path for a language: ("kn", "/vtu/cse") → "/kn/vtu/cse". */
export function localePath(lang: Lang, path: string) {
  if (lang === "en") return path;
  return path === "/" ? `/${lang}` : `/${lang}${path}`;
}

/** Google Translate proxy URL for an English-only page. */
export function translateProxyUrl(lang: Lang, path: string) {
  return `https://vtuhub-site.translate.goog${path}?_x_tr_sl=en&_x_tr_tl=${lang}&_x_tr_hl=${lang}`;
}

/** English paths that have hand-translated /kn and /hi versions. */
export function hasTranslation(path: string) {
  return (
    path === "/" ||
    path === "/vtu" ||
    path === "/faq" ||
    path === "/tools" ||
    /^\/tools\/[a-z]+$/.test(path) ||
    /^\/vtu\/[a-z]+$/.test(path) ||
    /^\/vtu\/[a-z]+\/[1-8](st|nd|rd|th)-semester$/.test(path)
  );
}

